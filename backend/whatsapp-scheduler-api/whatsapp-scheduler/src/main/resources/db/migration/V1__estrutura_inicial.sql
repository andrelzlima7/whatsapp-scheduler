CREATE TABLE usuario (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login varchar(100) NOT NULL UNIQUE,
    senha_hash varchar(100) NOT NULL
);

CREATE TABLE grupo_whatsapp (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    whatsapp_id varchar(100) NOT NULL UNIQUE,
    nome varchar(255) NOT NULL,
    somente_administradores boolean NOT NULL DEFAULT false,
    ativo boolean NOT NULL DEFAULT true,
    sincronizado_em timestamptz NOT NULL
);

CREATE TABLE agendamento (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_id bigint NOT NULL REFERENCES grupo_whatsapp(id),
    texto text NOT NULL CHECK (char_length(texto) BETWEEN 1 AND 10000 AND texto ~ '\S'),
    frequencia varchar(20) NOT NULL CHECK (frequencia IN ('DIARIA', 'SEMANAL', 'MENSAL')),
    horario time NOT NULL,
    dia_semana varchar(10) CHECK (dia_semana IN ('SEGUNDA','TERCA','QUARTA','QUINTA','SEXTA','SABADO','DOMINGO')),
    dia_mes integer CHECK (dia_mes BETWEEN 1 AND 31),
    ultimo_dia_mes boolean NOT NULL DEFAULT false,
    inicio_vigencia date NOT NULL,
    fim_vigencia date,
    fuso_horario varchar(100) NOT NULL,
    status varchar(20) NOT NULL CHECK (status IN ('ATIVO','PAUSADO','CANCELADO')),
    proxima_execucao_em timestamptz,
    criado_em timestamptz NOT NULL,
    atualizado_em timestamptz NOT NULL,
    versao bigint NOT NULL DEFAULT 0,
    CONSTRAINT ck_vigencia CHECK (fim_vigencia IS NULL OR fim_vigencia >= inicio_vigencia),
    CONSTRAINT ck_recorrencia CHECK (
        (frequencia = 'DIARIA' AND dia_semana IS NULL AND dia_mes IS NULL AND NOT ultimo_dia_mes) OR
        (frequencia = 'SEMANAL' AND dia_semana IS NOT NULL AND dia_mes IS NULL AND NOT ultimo_dia_mes) OR
        (frequencia = 'MENSAL' AND dia_semana IS NULL AND
            ((ultimo_dia_mes AND dia_mes IS NULL) OR (NOT ultimo_dia_mes AND dia_mes IS NOT NULL)))
    )
);
CREATE INDEX ix_agendamento_vencido ON agendamento(proxima_execucao_em, id) WHERE status = 'ATIVO';
CREATE INDEX ix_agendamento_grupo ON agendamento(grupo_id);

CREATE TABLE execucao_agendamento (
    id uuid PRIMARY KEY,
    agendamento_id bigint NOT NULL REFERENCES agendamento(id),
    previsto_em timestamptz NOT NULL,
    grupo_whatsapp_id varchar(100) NOT NULL,
    texto text NOT NULL,
    limite_envio_em timestamptz NOT NULL,
    status varchar(30) NOT NULL CHECK (status IN ('PENDENTE','EM_EXECUCAO','AGUARDANDO_NOVA_TENTATIVA','ENVIADO','FALHOU','INCERTO','EXPIRADO','CANCELADO')),
    tentativas integer NOT NULL DEFAULT 0 CHECK (tentativas >= 0),
    proxima_tentativa_em timestamptz,
    iniciado_em timestamptz,
    finalizado_em timestamptz,
    mensagem_whatsapp_id varchar(200),
    codigo_erro varchar(100),
    resultado_indeterminado boolean NOT NULL DEFAULT false,
    versao bigint NOT NULL DEFAULT 0,
    CONSTRAINT uk_execucao_ocorrencia UNIQUE(agendamento_id, previsto_em)
);
CREATE INDEX ix_execucao_pendente ON execucao_agendamento(proxima_tentativa_em, id)
    WHERE status IN ('PENDENTE','AGUARDANDO_NOVA_TENTATIVA','EM_EXECUCAO');
